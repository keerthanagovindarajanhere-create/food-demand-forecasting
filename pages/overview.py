import pandas as pd
import plotly.graph_objects as go
import streamlit as st

import ui

m = ui.headline_metrics()
v = ui.validation()
base = m["baselines"]
seasonal_mae = float(base.loc[base["Model"].str.startswith("Seasonal"), "MAE"].iloc[0])
improvement = (seasonal_mae - m["xgb_mae"]) / seasonal_mae * 100

st.title("🍽️ FOODFLOW")
st.markdown("#### Food demand forecasting and smart preparation planning")

st.markdown(
    """
**Problem.** Stores that sell food have to decide every day how much to stock or prepare.
Too little means empty shelves and lost sales; too much means waste. Demand changes with the
store, the product family, the day of the week, promotions and recent sales, so a fixed rule
of thumb does not work well.

**Objective.** Forecast daily demand for each store and product family from historical sales,
compare it honestly against simple baselines, study *where* the model fails, and turn a
forecast into an illustrative preparation quantity.
"""
)

# ------------------------------------------------------------ KPIs
st.subheader("Verified model performance")
st.caption(
    f"Computed live from the saved validation predictions ({m['n_val']:,} observations, "
    "2017-07-19 to 2017-08-15). Lower is better."
)
c = st.columns(4)
ui.kpi(c[0], "XGBoost MAE", f"{m['xgb_mae']:.2f}", "units per store-family-day")
ui.kpi(c[1], "XGBoost RMSE", f"{m['xgb_rmse']:.2f}", "penalises large misses")
ui.kpi(c[2], "Better than seasonal naive", f"{improvement:.1f}%",
       f"MAE {seasonal_mae:.2f} → {m['xgb_mae']:.2f}")
ui.kpi(c[3], "Error from top 1% of rows", f"{m['top1']:.2f}%",
       "share of total squared error")

st.write("")

# ------------------------------------------------------------ Baselines vs XGB
left, right = st.columns([3, 2])
with left:
    st.subheader("Baselines vs XGBoost")
    comp = pd.concat([
        base[["Model", "MAE", "RMSE", "RMSLE"]],
        pd.DataFrame([{"Model": "Reference XGBoost", "MAE": m["xgb_mae"],
                       "RMSE": m["xgb_rmse"], "RMSLE": m["xgb_rmsle"]}]),
    ], ignore_index=True)
    metric = st.radio("Metric", ["MAE", "RMSE"], horizontal=True, label_visibility="collapsed")
    colors = [ui.BASELINE] * (len(comp) - 1) + [ui.REFERENCE]
    fig = go.Figure(go.Bar(
        x=comp[metric], y=comp["Model"], orientation="h", marker_color=colors,
        text=comp[metric].map(lambda x: f"{x:.2f}"), textposition="outside",
    ))
    fig.update_layout(xaxis_title=f"Validation {metric} (lower is better)", hovermode="closest")
    fig.update_yaxes(autorange="reversed")
    st.plotly_chart(ui.style_fig(fig, 300), width="stretch")

with right:
    st.subheader("Full comparison")
    st.dataframe(
        comp.style.format({"MAE": "{:.2f}", "RMSE": "{:.2f}", "RMSLE": "{:.3f}"}),
        hide_index=True, width="stretch",
    )
    st.caption(
        "XGBoost clearly wins on MAE and RMSE. It does **not** win on RMSLE, which weights "
        "relative errors on small/zero-demand series heavily. The model was optimised for "
        "absolute error, so this is reported rather than hidden."
    )

# ------------------------------------------------------------ Key finding
st.subheader("Key research finding")
k1, k2 = st.columns(2)
with k1:
    st.info(
        f"**Errors are extremely concentrated.** The {-(-m['n_val'] // 100):,} worst validation "
        f"observations (top 1%) produce **{m['top1']:.2f}%** of all squared error, and the "
        f"top 5% produce **{m['top5']:.2f}%**. These are mostly high-demand rows "
        "(BEVERAGES, GROCERY I, CLEANING in large stores)."
    )
with k2:
    st.info(
        f"**Tail-weighting helps a little.** Giving high-demand training rows twice the weight "
        f"lowered MAE from {m['xgb_mae']:.2f} to {m['tail_mae']:.2f} and RMSE from "
        f"{m['xgb_rmse']:.2f} to {m['tail_rmse']:.2f}. The gain is modest and comes with "
        "slightly worse normal-demand RMSE and more high-demand over-prediction bias."
    )

# ------------------------------------------------------------ Dataset
st.subheader("Dataset")
d = st.columns(5)
ui.kpi(d[0], "Stores", f"{v['store_nbr'].nunique()}")
ui.kpi(d[1], "Product families", f"{v['family'].nunique()}")
ui.kpi(d[2], "Store-family series", f"{v.groupby(['store_nbr', 'family']).ngroups:,}")
ui.kpi(d[3], "Training rows", "3,000,888", "2013-01-01 to 2017-08-15")
ui.kpi(d[4], "Zero-sales rows", "31.30%", "demand is sparse and skewed")
st.caption(
    "Source: Kaggle *Store Sales – Time Series Forecasting* (Corporación Favorita, Ecuador). "
    "Store/family/series counts are computed from the saved validation results; training-set "
    "totals come from `docs/DATASET_PROFILE.md` (generated by `scripts/profile_dataset.py`), "
    "because the raw 3M-row CSV is not shipped with the repository."
)

with st.expander("Methodology in brief"):
    st.markdown(
        """
- **Temporal split:** train 2013-01-01 → 2017-07-18, validate 2017-07-19 → 2017-08-15 (28 days, 49,896 rows). No shuffling, so the model is always tested on the future.
- **Features (51):** lags 1/7/14/28, rolling means 7/14/28 (shifted so they only use past days), calendar fields, promotion count, store number, one-hot product family.
- **Model:** XGBoost, 500 trees, learning rate 0.05, max depth 8, subsample 0.8, colsample 0.8, min child weight 5. Predictions clipped at 0.
- **Baselines:** naive (yesterday), seasonal naive (same weekday last week), 7-day moving average.
- **Research analysis:** error by demand magnitude, cumulative squared-error concentration, family/store/date breakdowns, and a controlled tail-weighted retraining experiment (weight 2.0 above the training 80th percentile, 298 units).
"""
    )
